def get_arabic_stock_name(ticker: str, fallback: Optional[str] = None) -> str:
    """إرجاع الاسم العربي الأنيق والصحيح للسهم بناءً على رمزه."""
    clean_tk = ticker.strip().upper().replace('.CA', '')
    if clean_tk in ARABIC_STOCK_NAMES:
        return ARABIC_STOCK_NAMES[clean_tk]
    
    # إذا كان الاسم البديل يحتوي بالفعل على حروف عربية، نستخدمه
    if fallback and any('\u0600' <= c <= '\u06FF' for c in fallback):
        return fallback.strip()

    return fallback or clean_tk

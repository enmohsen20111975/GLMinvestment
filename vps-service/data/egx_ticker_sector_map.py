def get_sector_by_ticker(ticker: str) -> str:
    """Get official sector for a ticker."""
    return TICKER_SECTOR_MAP.get(ticker.upper(), None)


def get_all_mapped_tickers():
    """Get all mapped tickers."""
    return list(TICKER_SECTOR_MAP.keys())


if __name__ == "__main__":
    print(f"Total mapped tickers: {len(TICKER_SECTOR_MAP)}")

    # Count by sector
    sectors = {}
    for ticker, sector in TICKER_SECTOR_MAP.items():
        if sector not in sectors:
            sectors[sector] = []
        sectors[sector].append(ticker)

    print("\nBy Sector:")
    for sector, tickers in sorted(sectors.items(), key=lambda x: -len(x[1])):
        print(f"  {sector}: {len(tickers)}")

def get_sector(stock_name: str) -> str:
    """
    الحصول على قطاع السهم
    
    Args:
        stock_name: اسم السهم (يمكن يكون جزء من الاسم)
    
    Returns:
        اسم القطاع أو 'غير مصنف' إذا لم يوجد
    """
    stock_name = stock_name.strip()
    
    # Direct match
    if stock_name in STOCK_SECTORS:
        return STOCK_SECTORS[stock_name]
    
    # Partial match
    for key, sector in STOCK_SECTORS.items():
        if key in stock_name or stock_name in key:
            return sector
    
    return "غير مصنف"


def get_sector_english(sector_ar: str) -> str:
    """الحصول على اسم القطاع بالإنجليزية"""
    return EGX_OFFICIAL_SECTORS.get(sector_ar, "Unclassified")


def get_stocks_in_sector(sector: str) -> list:
    """الحصول على قائمة الأسهم في قطاع معين"""
    return [stock for stock, s in STOCK_SECTORS.items() if s == sector]


def get_all_sectors() -> dict:
    """الحصول على كل القطاعات"""
    return EGX_OFFICIAL_SECTORS.copy()



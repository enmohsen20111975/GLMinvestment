# بادئات الـ ISIN المعروفة (للتطبيع)
_EGX_ISIN_PREFIXES = ("EGS",)


def normalize_symbol(raw):
    """تطبيع أي رمز سهم وارد → {ticker, name_ar, sector}.

    يحل 4 أنواع من المشاكل:
    1. ISIN code (EGS30AJ1C016-EGP) → يحل الاسم من EGX_ISIN_NAMES.
    2. اسم مدمج (ORDSOOREDOOD) → يستخرج الرمز بالبادئة (ORDS).
    3. رمز مع لاحقة (COMI.CA, COMI-EGP) → يشيل اللاحقة.
    4. رمز نظيف → يرجّعه زي ما هو + يجيب الاسم.

    Args:
        raw: رمز أو اسم سهم وارد من أي مصدر (EGXPilot/TradingView/DB).

    Returns:
        dict: {ticker (str), name_ar (str|None), sector (str|None), is_isin (bool)}
        لو ما قدرش يحل الرمز، name_ar بتبقى None.
    """
    if not raw:
        return {"ticker": "", "name_ar": None, "sector": None, "is_isin": False}
    s = str(raw).strip().upper()

    # 1) ISIN code (EGS...)
    for prefix in _EGX_ISIN_PREFIXES:
        if s.startswith(prefix):
            # جرّب الـ ISIN الكامل، ثم بدون -EGP
            if s in EGX_ISIN_NAMES:
                name, sec = EGX_ISIN_NAMES[s]
                return {"ticker": s, "name_ar": name, "sector": sec, "is_isin": True}
            base = s.split("-")[0]
            if base in EGX_ISIN_NAMES:
                name, sec = EGX_ISIN_NAMES[base]
                return {"ticker": s, "name_ar": name, "sector": sec, "is_isin": True}
            # ISIN غير معروف → رجّع الـ ISIN زي ما هو بدون اسم
            return {"ticker": s, "name_ar": None, "sector": None, "is_isin": True}

    # 2) شيل اللواحق (.CA, .SR, -EGP, -USD) — جرّب المطابقة بعد الشيل
    for sep in (".", "-"):
        if sep in s:
            base = s.split(sep)[0]
            if base in EGX_CANONICAL_TV:
                name, sec = EGX_CANONICAL_TV[base]
                return {"ticker": base, "name_ar": name, "sector": sec, "is_isin": False}

    # 3) مطابقة بالبادئة (للأسماء المدمجة: ORDSOOREDOOD → ORDS)
    for t in _EGX_CANONICAL_TICKERS:
        if s.startswith(t):
            name, sec = EGX_CANONICAL_TV[t]
            return {"ticker": t, "name_ar": name, "sector": sec, "is_isin": False}

    # 4) مطابقة مباشرة
    if s in EGX_CANONICAL_TV:
        name, sec = EGX_CANONICAL_TV[s]
        return {"ticker": s, "name_ar": name, "sector": sec, "is_isin": False}

    # 5) رمز غير معروف → رجّعه زي ما هو بدون اسم
    return {"ticker": s, "name_ar": None, "sector": None, "is_isin": False}


def get_canonical_name(raw):
    """اختصار: رجّع الاسم العربي للسهم، أو None."""
    return normalize_symbol(raw)["name_ar"]


def get_canonical_ticker(raw):
    """اختصار: رجّع الرمز النظيف للسهم."""
    return normalize_symbol(raw)["ticker"]


#!/bin/bash
# ============================================================================
# install-radar-update.sh — يطبّق تحديثات الرادار على الـ VPS
# ============================================================================
# هذا السكريبت:
#   1. ينزّل tarball الكود المعدّل من الـ sandbox
#   2. يعمل backup للملفات الحالية
#   3. يستخرج الملفات الجديدة
#   4. يعمل commit + push على GitHub (من الـ VPS اللي عنده credentials)
#   5. يعيد تشغيل Next.js
#   6. يشغّل أول warmup للرادار
#
# الاستخدام:
#   cd /root/GLMinvestment
#   bash install-radar-update.sh
# ============================================================================

set -e  # أوقف عند أي خطأ

PROJECT_DIR="/root/GLMinvestment"
SANDBOX_URL="http://localhost:3001/radar-source-update.tar.gz"
# لو الـ sandbox مش على localhost، بدّل الـ URL ده بالـ URL الكامل

cd "$PROJECT_DIR"

echo "════════════════════════════════════════════════════════════"
echo "  تثبيت تحديثات رادار الميكرز"
echo "════════════════════════════════════════════════════════════"
echo ""

# ─── 1. تنزيل الـ tarball ─────────────────────────────────────
echo "⬇️  [1/6] تنزيل الكود المعدّل..."
if command -v curl &> /dev/null; then
    curl -sL -o /tmp/radar-source-update.tar.gz "$SANDBOX_URL"
elif command -v wget &> /dev/null; then
    wget -q -O /tmp/radar-source-update.tar.gz "$SANDBOX_URL"
else
    echo "❌ مفيش curl أو wget متثبت. ثبّت واحد منهم الأول."
    exit 1
fi

if [ ! -f /tmp/radar-source-update.tar.gz ] || [ ! -s /tmp/radar-source-update.tar.gz ]; then
    echo "❌ فشل تنزيل الملف. تأكد إن الـ sandbox شغال والـ URL صح."
    echo "   URL: $SANDBOX_URL"
    exit 1
fi
echo "   ✅ اتنزّل $(du -h /tmp/radar-source-update.tar.gz | cut -f1)"

# ─── 2. Backup الملفات الحالية ────────────────────────────────
echo ""
echo "💾 [2/6] عمل backup للملفات الحالية..."
BACKUP_DIR="/root/GLMinvestment-backup-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP_DIR"

# انسخ بس الملفات اللي هتتغير
for f in $(tar tzf /tmp/radar-source-update.tar.gz); do
    if [ -f "$PROJECT_DIR/$f" ]; then
        mkdir -p "$BACKUP_DIR/$(dirname $f)"
        cp "$PROJECT_DIR/$f" "$BACKUP_DIR/$f"
    fi
done
echo "   ✅ Backup في: $BACKUP_DIR"

# ─── 3. استخراج الملفات الجديدة ───────────────────────────────
echo ""
echo "📦 [3/6] استخراج الملفات الجديدة..."
cd "$PROJECT_DIR"
tar xzf /tmp/radar-source-update.tar.gz
echo "   ✅ $(tar tzf /tmp/radar-source-update.tar.gz | wc -l) ملف اتحدث"

# ─── 4. Commit + Push على GitHub ───────────────────────────────
echo ""
echo "🔄 [4/6] رفع التحديثات على GitHub..."
cd "$PROJECT_DIR"
git add -A

# تأكد إن فيه تغييرات فعلاً
if git diff --cached --quiet; then
    echo "   ⚠️  مفيش تغييرات جديدة (الكود مطابق للي على GitHub)"
else
    git commit -m "feat(radar): production-safe cache architecture + portable python + V40.2 refresh endpoint

- radar-cache.ts: instant read + background warmup (no more 30s timeout)
- maker-radar/route.ts: serves cached JSON (<50ms response)
- maker-radar/warmup/route.ts: manual/cron trigger endpoint
- predictions/refresh-v40/route.ts: V40.2 generator via subprocess
- MakerRadarTab.tsx: freshness badge + refresh buttons
- maker_radar.py: db_source field in JSON output
- resolvePython(): 100% portable (no absolute paths)
- shared_liquidity.py: Kill Switch + Money Flow + Life Cycle
- v40_2_daily_generator.py: integrated radar veto + boost
- liquidity_filter.py: dynamic thresholds 80K/200K/400K

Generated by sandbox install script on $(date -u +%Y-%m-%dT%H:%M:%SZ)"

    # محاولة push (3 مرات)
    for i in 1 2 3; do
        if git push origin main 2>&1; then
            echo "   ✅ اترفع على GitHub بنجاح"
            break
        else
            echo "   ⚠️  محاولة $i فشلت — إعادة المحاولة بعد 3 ثواني..."
            sleep 3
            if [ $i -eq 3 ]; then
                echo "   ❌ فشل الـ push 3 مرات. اتأكد من GitHub credentials:"
                echo "      git config --global credential.helper store"
                echo "      ثم اعمل git push يدوياً"
            fi
        fi
    done
fi

# ─── 5. إعادة تشغيل Next.js ────────────────────────────────────
echo ""
echo "🔄 [5/6] إعادة تشغيل Next.js..."
if command -v pm2 &> /dev/null; then
    pm2 restart nextjs
    echo "   ✅ Next.js اتrestart"
    echo "   ⏳ استنى 8 ثواني للسيرفر يقلع..."
    sleep 8
else
    echo "   ⚠️  pm2 مش متثبت — أعد تشغيل Next.js يدوياً"
fi

# ─── 6. أول warmup للرادار ─────────────────────────────────────
echo ""
echo "🎯 [6/6] تشغيل أول warmup للرادار..."
echo "   ⏳ بياخد حوالي 1-5 ثواني..."
WARMUP_RESULT=$(curl -s -X POST "http://localhost:3000/api/maker-radar/warmup?market=EGX&timeout=120000" 2>/dev/null || echo "FAILED")

if echo "$WARMUP_RESULT" | grep -q '"success":true'; then
    DURATION=$(echo "$WARMUP_RESULT" | grep -o '"last_warmup_duration_ms":[0-9]*' | cut -d: -f2)
    SCANNED=$(echo "$WARMUP_RESULT" | grep -o '"cache_total_scanned":[0-9]*' | cut -d: -f2)
    DB_SOURCE=$(echo "$WARMUP_RESULT" | grep -o '"db_source":"[^"]*"' | cut -d: -f2- | tr -d '"')
    echo "   ✅ الرادار جاهز!"
    echo "      • المدة: ${DURATION}ms"
    echo "      • الأسهم المفحوصة: $SCANNED"
    echo "      • قاعدة البيانات: $DB_SOURCE"
else
    echo "   ⚠️  الـ warmup ممكن يكون لسه بيسخن — جرّب:"
    echo "      curl -X POST 'http://localhost:3000/api/maker-radar/warmup?market=EGX'"
fi

echo ""
echo "════════════════════════════════════════════════════════════"
echo "  ✅ خلصت! افتح الموقع وتأكد إن الرادار شغال"
echo "════════════════════════════════════════════════════════════"
echo ""
echo "📋 الخطوات اللي اتعملت:"
echo "   1. ✅ تنزيل الكود من الـ sandbox"
echo "   2. ✅ Backup في: $BACKUP_DIR"
echo "   3. ✅ استخراج 27 ملف"
echo "   4. ✅ Commit + Push على GitHub"
echo "   5. ✅ إعادة تشغيل Next.js"
echo "   6. ✅ أول warmup للرادار"
echo ""
echo "🔧 لو حصلت مشكلة، استرجع من الـ backup:"
echo "   cp -r $BACKUP_DIR/* /root/GLMinvestment/"
echo ""
echo "📋 أضف الـ cron jobs دي (crontab -e):"
echo "   PATH=/root/GLMinvestment/.venv/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
echo "   */5 10-14 * * 1-5 curl -s -X POST 'http://localhost:3000/api/maker-radar/warmup?market=EGX' >> /tmp/radar-cron.log 2>&1"
echo "   30 14 * * 1-5 curl -s -X POST 'http://localhost:3000/api/predictions/refresh-v40?mode=today' >> /tmp/v40-cron.log 2>&1"

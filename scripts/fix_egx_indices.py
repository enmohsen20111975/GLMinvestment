INDICES = [
    ('EGX30', EGX30_DATA),
    ('EGX70', EGX70_DATA),
    ('EGX33', EGX33_DATA),
    ('EGX100', EGX100_DATA),
]

def parse_and_seed(conn, symbol, raw_data):
    """Parse Arabic date rows + seed into index_daily_prices."""
    rows = []
    for line in raw_data.strip().split('\n'):
        parts = [p.strip() for p in line.split('\t')]
        if len(parts) < 5: continue
        date = parse_date(parts[0])
        if not date: continue
        open_ = parse_num(parts[1])
        high = parse_num(parts[2])
        low = parse_num(parts[3])
        close = parse_num(parts[4])
        change_pct = parse_num(parts[6]) if len(parts) > 6 else 0.0
        rows.append((symbol, date, open_, high, low, close, 0, change_pct))

    for r in rows:
        conn.execute(
            "INSERT OR REPLACE INTO index_daily_prices "
            "(symbol, price_date, open, high, low, close, volume, change_percent) "
            "VALUES (?,?,?,?,?,?,?,?)", r
        )
    return len(rows)


def main():
    if not STOCKS_DB.exists():
        print(f"✗ stocks.db not found at {STOCKS_DB}")
        sys.exit(1)

    conn = sqlite3.connect(str(STOCKS_DB))
    conn.execute("""
        CREATE TABLE IF NOT EXISTS index_daily_prices (
            symbol TEXT, price_date TEXT, open REAL, high REAL, low REAL,
            close REAL, volume REAL, change_percent REAL,
            PRIMARY KEY (symbol, price_date))
    """)

    # 1. امسح كل القيم البايظة
    deleted = conn.execute(
        "DELETE FROM index_daily_prices WHERE symbol IN ('EGX30','EGX70','EGX100','EGX33')"
    ).rowcount
    conn.commit()
    print(f"✓ مسحت {deleted} صف بايظ من index_daily_prices")

    # 2. حط القيم الحقيقية لكل مؤشر
    total = 0
    for symbol, raw_data in INDICES:
        n = parse_and_seed(conn, symbol, raw_data)
        conn.commit()
        latest = conn.execute(
            "SELECT price_date, close FROM index_daily_prices WHERE symbol=? "
            "ORDER BY price_date DESC LIMIT 1", (symbol,)
        ).fetchone()
        print(f"  ✓ {symbol}: {n} صف — آخر قيمة {latest[0]}: {latest[1]:,.2f}")
        total += n

    conn.close()
    print(f"\n✅ خلصت! {total} صف حقيقي لـ 4 مؤشرات (EGX30 + EGX70 + EGX33 + EGX100)")
    print(f"   شغّل: python3 scripts/sync_market_indices_live.py")


if __name__ == "__main__":
    main()

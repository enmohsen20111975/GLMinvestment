#!/usr/bin/env python3
"""
seed_live_intraday_session.py — SYNTHETIC Intraday Session Seeder (EGX)
=======================================================================

⚠️  Rule 27 (NO-FAKE-DATA) DISCLAIMER  ⚠️
------------------------------------------
This script seeds SYNTHETIC (simulated — NOT real market) intraday OHLC bars
into ``db/intraday.db.stock_intraday`` for the SOLE purpose of activating the
Intraday CVD Flow + Maker Radar Snapshot UI components during development /
demo. The bars are generated by a deterministic random walk anchored on the
REAL ``current_price`` value pulled from ``db/stocks.db.stocks`` for each
EGX30 ticker; everything else (per-bar OHLC, volume, whale blocks) is
synthetic and must NOT be presented as historical market data.

When the live ingestion pipeline (``vps-service/jobs/intraday_scanner.py``)
is wired back up, real bars for the same ``(ticker, timestamp)`` will
overwrite these synthetic ones automatically (UNIQUE constraint + INSERT OR
REPLACE), so this seeder is safe to re-run any time the UI needs a fixture.

Recipe (15 EGX30 tickers × 54 bars × 5-min interval):
    Session window : 10:00 → 14:30 EGX  (4.5h = 270 min)
    Bars per ticker: 54  (timestamps 10:00, 10:05, …, 14:25)
    Total rows     : 15 × 54 = 810
    Whale blocks   : ~10% of bars per ticker with notional = price × volume
                     strictly greater than 100,000 EGP  → activates the
                     Large Blocks aggregation in ``src/lib/intraday-flow.ts``.

Idempotent
----------
Re-running with the same ``--date`` is safe: rows are upserted via
``INSERT OR REPLACE`` keyed on the ``UNIQUE(ticker, timestamp)`` constraint.
A stable per-(ticker, date) SHA-256 seed makes regeneration deterministic —
two runs against the same date produce byte-identical rows (modulo float
rounding), so the UI never flickers between refreshes.

Usage
-----
Dry-run (DEFAULT — prints full report, writes nothing):

    python3 scripts/seed_live_intraday_session.py

Real run (writes 810 rows to db/intraday.db, after backup):

    python3 scripts/seed_live_intraday_session.py --execute

Custom session date:

    python3 scripts/seed_live_intraday_session.py --date 2026-10-12 --execute

References:
    - Task ID: P0-ALPHA-INTRADAY-SEEDER
    - Rule 27 (NO-FAKE-DATA), Rule 67 (SSOT)
    - src/lib/intraday-flow.ts        (consumer of stock_intraday)
    - src/app/api/stocks/[ticker]/intraday-flow/route.ts
"""
from __future__ import annotations

import argparse
import hashlib
import os
import random
import shutil
import sqlite3
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

# ─── Paths ─────────────────────────────────────────────────────────────────

PROJECT_ROOT = Path(__file__).resolve().parent.parent
STOCKS_DB = PROJECT_ROOT / "db" / "stocks.db"
INTRADAY_DB = PROJECT_ROOT / "db" / "intraday.db"
BACKUP_DIR = PROJECT_ROOT / "db" / "backups"

# ─── EGX30 anchor tickers ──────────────────────────────────────────────────
# Entry price for each ticker is pulled LIVE from stocks.db.stocks.current_price.
# Order matches the task spec.

EGX30_TICKERS: tuple[str, ...] = (
    "EAST", "EFIH", "EGAL", "EMFD", "ETEL",
    "FWRY", "HELI", "ISPH", "MFPC", "PHDC",
    "RAYA", "RMDA", "SCTS", "TMGH", "VLMR",
)

MARKET = "EGX"

# ─── Session geometry ──────────────────────────────────────────────────────
# EGX trading session: 10:00 → 14:30 (4.5 hours = 270 minutes).
# 5-min intervals → 54 bars. Timestamp = OPEN time of each 5-min bar.
# (last bar timestamp = 14:25, whose close is the session close at 14:30).

SESSION_START_HOUR = 10
SESSION_START_MIN = 0
SESSION_END_HOUR = 14
SESSION_END_MIN = 30  # exclusive upper bound on timestamps (close of last bar).
BAR_INTERVAL_MIN = 5
BARS_PER_TICKER = 54  # 270 / 5 — sanity guard.

# ─── Random-walk parameters ───────────────────────────────────────────────
# Per-bar volatility: ±0.5% on top of a directional drift chosen per ticker
# so each session produces a believable up / down / range profile.

WALK_VOLATILITY = 0.005          # ±0.5% per bar.
TREND_DRIFT_MAGNITUDE = 0.0003   # 0.03% drift per bar in the chosen direction.

# Intrabar spike/dip magnitude (as fraction of price).
SPIKE_MIN_FRAC = 0.0005  # 0.05%
SPIKE_MAX_FRAC = 0.0020  # 0.20%

# ─── Volume distribution (notional-targeted) ──────────────────────────────
# The task spec literally says "volume ∈ [1000, 50000]" for retail bars.
# But for high-priced tickers (EGAL @ 335, SCTS @ 549) the smallest volume
# in that range already produces notional > 100K EGP, which would force
# EVERY retail bar to be classified as a whale block by the API classifier
# (LARGE_BLOCK_NOTIONAL_EGP = 100_000 in src/lib/intraday-flow.ts).
#
# To keep the ~10% whale ratio meaningful across all price levels, we
# derive volume from a notional TARGET rather than a fixed share range:
#
#   - RETAIL bar  → notional ∈ [5K,  80K] EGP  → volume = notional / price
#   - WHALE  bar  → notional ∈ [100K, 500K] EGP → volume = notional / price
#
# This matches the task's worked example: ETEL price=147.87, volume=800 →
# notional=118,296 → whale block ✅. Volume CAN be < 1000 for high-priced
# tickers when the notional target requires it (explicitly permitted by
# the task's example).

RETAIL_NOTIONAL_MIN = 5_000       # EGP
RETAIL_NOTIONAL_MAX = 80_000      # EGP  (10K headroom under the 100K threshold)

# ─── Whale-block simulation ───────────────────────────────────────────────
# ~10% of bars per ticker carry a notional = price × volume strictly
# greater than 100,000 EGP, so the Large-Blocks classifier in
# src/lib/intraday-flow.ts (LARGE_BLOCK_NOTIONAL_EGP = 100_000) lights up.

WHALE_BLOCK_FRACTION = 0.10
WHALE_BLOCK_NOTIONAL_MIN = 100_000      # EGP — matches src/lib/intraday-flow.ts.
WHALE_BLOCK_NOTIONAL_MAX = 500_000       # EGP — comfortable upper bound for demo.

# Volume floor (shares). Never emit a zero-volume bar.
VOLUME_FLOOR = 100

# ─── Stable seeding ────────────────────────────────────────────────────────
# Deterministic per-(ticker, date) seed → identical bars on re-runs.

_SEED_SALT = "EGX-INTRADAY-SEEDER-v1"


def build_session_timestamps(session_date: str) -> list[str]:
    """Return 54 ISO timestamps: 10:00, 10:05, …, 14:25 (5-min step)."""
    base = datetime.fromisoformat(f"{session_date}T10:00:00")
    end = datetime.fromisoformat(f"{session_date}T14:30:00")
    out: list[str] = []
    cur = base
    while cur < end:
        out.append(cur.isoformat(timespec="seconds"))
        cur += timedelta(minutes=BAR_INTERVAL_MIN)
    if len(out) != BARS_PER_TICKER:
        raise RuntimeError(
            f"session geometry broken: got {len(out)} timestamps, "
            f"expected {BARS_PER_TICKER}"
        )
    return out


def fetch_entry_prices(tickers: tuple[str, ...]) -> dict[str, float]:
    """Pull the REAL current_price for each ticker from db/stocks.db.stocks."""
    if not STOCKS_DB.exists():
        raise FileNotFoundError(f"stocks.db not found at {STOCKS_DB}")
    prices: dict[str, float] = {}
    con = sqlite3.connect(STOCKS_DB)
    try:
        for t in tickers:
            row = con.execute(
                "SELECT current_price FROM stocks WHERE ticker = ?",
                (t,),
            ).fetchone()
            if not row or row[0] in (None, 0) or not isinstance(row[0], (int, float)):
                print(
                    f"[WARN] ticker={t} missing/invalid current_price in stocks.db",
                    file=sys.stderr,
                )
                continue
            prices[t] = float(row[0])
    finally:
        con.close()
    return prices


def deterministic_seed(ticker: str, session_date: str) -> int:
    """Stable per-(ticker, date) RNG seed → byte-identical re-runs."""
    key = f"{ticker}|{session_date}|{_SEED_SALT}"
    digest = hashlib.sha256(key.encode("utf-8")).hexdigest()
    return int(digest[:8], 16)


def generate_bars_for_ticker(
    ticker: str,
    entry_price: float,
    timestamps: list[str],
) -> list[dict]:
    """Build 54 synthetic OHLC bars for a single ticker (deterministic)."""
    rng = random.Random(deterministic_seed(ticker, timestamps[0][:10]))

    # Pick a per-session directional bias: -1 / 0 / +1 with mild tilt.
    direction = rng.choice([-1, -1, 0, 1, 1])
    drift = direction * TREND_DRIFT_MAGNITUDE

    # Pre-select whale-block bar indices (~10% of bars, at least 1).
    n_bars = len(timestamps)
    n_whales = max(1, round(n_bars * WHALE_BLOCK_FRACTION))
    whale_idx = set(rng.sample(range(n_bars), n_whales))

    bars: list[dict] = []
    prev_close = entry_price

    for i, ts in enumerate(timestamps):
        # Random-walk step: directional drift + symmetric noise.
        step = drift + rng.uniform(-WALK_VOLATILITY, WALK_VOLATILITY)
        close = round(prev_close * (1 + step), 4)
        # Guard against pathological negatives (shouldn't happen but be safe).
        if close <= 0:
            close = round(prev_close * (1 + abs(step)), 4)

        open_price = round(prev_close, 4)

        # Intrabar high/low: small spike above max(o,c), dip below min(o,c).
        spike = prev_close * rng.uniform(SPIKE_MIN_FRAC, SPIKE_MAX_FRAC)
        dip = prev_close * rng.uniform(SPIKE_MIN_FRAC, SPIKE_MAX_FRAC)
        high = round(max(open_price, close) + spike, 4)
        low = round(min(open_price, close) - dip, 4)
        if low <= 0:
            low = round(min(open_price, close) * 0.995, 4)

        # Volume: retail vs whale block (notional-targeted; see module header).
        if i in whale_idx:
            # Force notional into [100K, 500K] EGP → guaranteed whale block.
            notional_target = rng.uniform(
                WHALE_BLOCK_NOTIONAL_MIN, WHALE_BLOCK_NOTIONAL_MAX
            )
            volume = max(VOLUME_FLOOR, int(notional_target / close))
            # Belt-and-braces: guarantee the notional actually crosses the line.
            if volume * close <= WHALE_BLOCK_NOTIONAL_MIN:
                volume = int(WHALE_BLOCK_NOTIONAL_MIN / close) + 1
        else:
            # Retail notional ∈ [5K, 80K] EGP → guaranteed retail.
            notional_target = rng.uniform(
                RETAIL_NOTIONAL_MIN, RETAIL_NOTIONAL_MAX
            )
            volume = max(VOLUME_FLOOR, int(notional_target / close))

        change_percent = round(
            (close - entry_price) / entry_price * 100, 4
        )

        bars.append({
            "ticker": ticker,
            "market": MARKET,
            "timestamp": ts,
            "price": close,           # close of the 5-min bar.
            "open": open_price,
            "high": high,
            "low": low,
            "close": close,
            "volume": volume,
            "change_percent": change_percent,
        })

        prev_close = close

    return bars


# ─── Backup + write ───────────────────────────────────────────────────────

def backup_intraday_db() -> Path:
    """Copy db/intraday.db → db/backups/intraday_<UTC-timestamp>.db (pre-mutation)."""
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup_path = BACKUP_DIR / f"intraday_{ts}.db"
    shutil.copy2(INTRADAY_DB, backup_path)
    return backup_path


def upsert_bars(rows: list[dict]) -> int:
    """INSERT OR REPLACE bars into stock_intraday (idempotent via UNIQUE(ticker,timestamp))."""
    if not INTRADAY_DB.exists():
        raise FileNotFoundError(f"intraday.db not found at {INTRADAY_DB}")
    con = sqlite3.connect(INTRADAY_DB)
    try:
        cur = con.cursor()
        # Defensive: make sure the UNIQUE(ticker, timestamp) index exists so
        # INSERT OR REPLACE actually behaves as upsert (table already has it
        # per schema, but this is a no-op if duplicate).
        cur.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS ux_stock_intraday_ticker_ts
                ON stock_intraday(ticker, timestamp)
            """
        )
        written = 0
        for r in rows:
            cur.execute(
                """
                INSERT OR REPLACE INTO stock_intraday
                    (ticker, market, timestamp, price,
                     change_percent, volume, open, high, low)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    r["ticker"], r["market"], r["timestamp"], r["price"],
                    r["change_percent"], r["volume"],
                    r["open"], r["high"], r["low"],
                ),
            )
            written += cur.rowcount
        con.commit()
        return written
    finally:
        con.close()


# ─── Verification ───────────────────────────────────────────────────────────

def verify(rows_count_expected: int) -> dict:
    con = sqlite3.connect(INTRADAY_DB)
    try:
        total = con.execute(
            "SELECT COUNT(*) FROM stock_intraday"
        ).fetchone()[0]

        per_ticker = con.execute(
            """
            SELECT ticker, COUNT(*) AS n
            FROM stock_intraday
            GROUP BY ticker
            ORDER BY ticker
            """
        ).fetchall()

        whale_count = con.execute(
            """
            SELECT COUNT(*) FROM stock_intraday
            WHERE price * volume > ?
            """,
            (WHALE_BLOCK_NOTIONAL_MIN,),
        ).fetchone()[0]

        # Sample a few whale rows for visual sanity.
        sample_whales = con.execute(
            """
            SELECT ticker, timestamp, price, volume,
                   ROUND(price * volume, 2) AS notional
            FROM stock_intraday
            WHERE price * volume > ?
            ORDER BY price * volume DESC
            LIMIT 5
            """,
            (WHALE_BLOCK_NOTIONAL_MIN,),
        ).fetchall()
    finally:
        con.close()

    print(f"[VERIFY] total rows in stock_intraday   = {total} "
          f"(expected {rows_count_expected}) "
          f"{'✅' if total == rows_count_expected else '❌'}")
    print(f"[VERIFY] distinct tickers              = {len(per_ticker)} "
          f"(expected 15) "
          f"{'✅' if len(per_ticker) == 15 else '❌'}")
    print(f"[VERIFY] bars per ticker               = "
          f"{', '.join(f'{t}={n}' for t, n in per_ticker)}")
    print(f"[VERIFY] whale blocks (notional > 100K) = {whale_count} "
          f"(target ~{rows_count_expected // 10}) "
          f"{'✅' if whale_count >= rows_count_expected // 12 else '⚠️'}")
    print("[VERIFY] top-5 whale bars by notional:")
    for ticker, ts, price, vol, notional in sample_whales:
        print(f"        {ticker:5s} {ts}  price={price:<10.4f} "
              f"vol={vol:<8d} notional={notional:>12,.2f} EGP")

    return {
        "total": total,
        "tickers": len(per_ticker),
        "whale_count": whale_count,
    }


# ─── CLI entry ──────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Seed SYNTHETIC intraday OHLC bars into db/intraday.db "
            "(Rule 27 disclaimer inside the module docstring)."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--date",
        default=datetime.now().strftime("%Y-%m-%d"),
        help="Session date YYYY-MM-DD (default: today UTC).",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help=(
            "Actually write rows to db/intraday.db. "
            "Without this flag the script runs in DRY-RUN mode "
            "(prints the report only, writes nothing)."
        ),
    )
    args = parser.parse_args()

    # Validate --date.
    try:
        datetime.strptime(args.date, "%Y-%m-%d")
    except ValueError:
        print(f"[ERROR] --date must be YYYY-MM-DD, got: {args.date!r}",
              file=sys.stderr)
        return 2

    # Banner.
    print("=" * 76)
    print("seed_live_intraday_session.py — SYNTHETIC intraday session seeder (EGX)")
    print("=" * 76)
    print("⚠️  Rule 27 (NO-FAKE-DATA) DISCLAIMER:")
    print("    Bars produced here are SYNTHETIC (deterministic random-walk")
    print("    simulation anchored on the REAL current_price pulled from")
    print("    stocks.db). They exist ONLY to activate the Intraday CVD Flow")
    print("    + Maker Radar Snapshot UI during dev / demo. They are NOT real")
    print("    market data. Production ingestion must overwrite them with real")
    print("    bars via vps-service/jobs/intraday_scanner.py + aggregator.")
    print("-" * 76)
    print(f"Session date    : {args.date}")
    print(f"Mode            : {'EXECUTE (write to DB)' if args.execute else 'DRY-RUN (no writes)'}")
    print(f"Tickers         : {len(EGX30_TICKERS)} EGX30")
    print(f"Bars per ticker : {BARS_PER_TICKER}  (5-min intervals, 10:00 → 14:30)")
    print(f"Expected rows   : {len(EGX30_TICKERS) * BARS_PER_TICKER}")
    print(f"Whale target    : ~{round(BARS_PER_TICKER * WHALE_BLOCK_FRACTION)} bars / ticker "
          f"with notional > {WHALE_BLOCK_NOTIONAL_MIN:,} EGP")
    print(f"Stocks DB       : {STOCKS_DB}")
    print(f"Intraday DB     : {INTRADAY_DB}")
    print("-" * 76)

    timestamps = build_session_timestamps(args.date)
    assert len(timestamps) == BARS_PER_TICKER
    print(f"[INFO] built {len(timestamps)} session timestamps "
          f"({timestamps[0]} → {timestamps[-1]})")

    entry_prices = fetch_entry_prices(EGX30_TICKERS)
    if len(entry_prices) != len(EGX30_TICKERS):
        missing = set(EGX30_TICKERS) - set(entry_prices)
        print(f"[ERROR] missing current_price for: {sorted(missing)}",
              file=sys.stderr)
        return 2
    print(f"[INFO] fetched REAL entry prices for {len(entry_prices)} tickers:")
    for t in EGX30_TICKERS:
        print(f"        {t:5s} entry_price = {entry_prices[t]:<10.4f}")

    # Generate synthetic bars.
    print("-" * 76)
    print("[PLAN] generating synthetic bars ...")
    all_rows: list[dict] = []
    whale_per_ticker: dict[str, int] = {}
    for t in EGX30_TICKERS:
        bars = generate_bars_for_ticker(t, entry_prices[t], timestamps)
        n_w = sum(
            1 for b in bars
            if b["price"] * b["volume"] > WHALE_BLOCK_NOTIONAL_MIN
        )
        whale_per_ticker[t] = n_w
        all_rows.extend(bars)
    print(f"[PLAN] total rows ready = {len(all_rows)}")
    print("[PLAN] whale blocks per ticker (target ≈ "
          f"{round(BARS_PER_TICKER * WHALE_BLOCK_FRACTION)}):")
    for t in EGX30_TICKERS:
        flag = "✅" if whale_per_ticker[t] >= 1 else "❌"
        print(f"        {t:5s} : {whale_per_ticker[t]} whale bars  {flag}")

    if not args.execute:
        print("-" * 76)
        print("[DRY-RUN] no rows written.")
        print("[DRY-RUN] re-run with --execute to commit (after auto-backup).")
        return 0

    # ─── EXECUTE PATH ──────────────────────────────────────────────────────
    print("-" * 76)
    print("[EXECUTE] step 1/3 — backing up db/intraday.db ...")
    backup_path = backup_intraday_db()
    backup_size = backup_path.stat().st_size
    print(f"[EXECUTE]        backup → {backup_path}  ({backup_size:,} bytes)")

    print("[EXECUTE] step 2/3 — INSERT OR REPLACE "
          f"{len(all_rows)} rows into stock_intraday ...")
    written = upsert_bars(all_rows)
    print(f"[EXECUTE]        wrote {written} rows (idempotent — safe to re-run)")

    print("[EXECUTE] step 3/3 — verification ...")
    verify(rows_count_expected=len(all_rows))

    return 0


if __name__ == "__main__":
    sys.exit(main())

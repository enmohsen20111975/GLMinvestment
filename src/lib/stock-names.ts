/**
 * Get stock name info by symbol
 */
export function getStockName(symbol: string): StockNameInfo | undefined {
  return STOCK_NAMES[symbol.toUpperCase()];
}

/**
 * Get stock name with fallback
 */
export function getStockNameWithFallback(symbol: string, name?: string | null): string {
  if (name && name.trim()) return name;
  return STOCK_NAMES[symbol.toUpperCase()]?.name || symbol;
}

/**
 * Get stock Arabic name with fallback
 */
export function getStockNameArWithFallback(symbol: string, nameAr?: string | null): string {
  if (nameAr && nameAr.trim()) return nameAr;
  return STOCK_NAMES[symbol.toUpperCase()]?.name_ar || symbol;
}

/**
 * Enrich stock data with names from mapping
 */
export function enrichStockData<T extends { symbol?: string; ticker?: string; name?: string | null; name_ar?: string | null }>(stock: T): T {
  const symbol = stock.symbol || stock.ticker || '';
  const nameInfo = STOCK_NAMES[symbol.toUpperCase()];
  
  if (!nameInfo) return stock;
  
  return {
    ...stock,
    name: stock.name || nameInfo.name,
    name_ar: stock.name_ar || nameInfo.name_ar,
  };
}

/**
 * Enrich array of stocks with names
 */
export function enrichStocksData<T extends { symbol?: string; ticker?: string; name?: string | null; name_ar?: string | null }>(stocks: T[]): T[] {
  return stocks.map(enrichStockData);
}


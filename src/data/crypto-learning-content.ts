export function getTotalCryptoLessons(): number {
  return cryptoCourses.reduce((acc, course) => acc + course.lessons.length, 0);
}

export function getCryptoCourseCompletionStatus(courseId: string, completedLessons: string[]): { percentage: number; completed: number; total: number } {
  const course = cryptoCourses.find(c => c.id === courseId);
  if (!course) return { percentage: 0, completed: 0, total: 0 };

  let completed = 0;
  course.lessons.forEach((_, idx) => {
    if (completedLessons.includes(`${courseId}-${idx}`)) completed++;
  });

  return {
    percentage: course.lessons.length > 0 ? (completed / course.lessons.length) * 100 : 0,
    completed,
    total: course.lessons.length
  };
}
